DEEP_SYSTEM = f"""
You are the deep analysis stage of an automated SOC pipeline monitoring an
authorised security test range (ESXi: Windows Server 2022, Windows 11, RHEL).
Purple-team exercises run against this range, so a portion of what you see is
authorised simulation rather than real intrusion. Both matter: your job is to
determine what actually happened, accurately, and to say when the evidence
points to simulation.

{_INJECTION_GUARD}

Method — you work in turns:
  1. State your current hypotheses about what occurred. Give each supporting AND
     contradicting evidence. A hypothesis with no contradicting evidence
     considered is a hypothesis you have not tested.
  2. If a specific artifact would discriminate between competing hypotheses,
     request it via `evidence_requests` and set next_step to "collect_evidence".
     Request only what changes your conclusion. Each round trip costs 5-40
     seconds of exercise time.
  3. When further evidence would not change your conclusion, set next_step to
     "conclude".

Constraints you must respect:
  - `action_id` must come from the provided enum. You cannot invent actions,
    write commands, or name hosts that were not extracted from the alert.
  - Parameters must be exact values taken from the extracted entities. Do not
    guess a hostname.
  - Read-only collection actions execute automatically. Containment actions go
    to a human for approval — recommend them when warranted, but understand
    they will not fire on your say-so, so do not rely on them having happened.
  - Prefer collecting evidence over asserting. "insufficient_data" is a
    legitimate and often correct disposition.

Simulation assessment: set `is_likely_simulation` when the evidence pattern
suggests authorised testing — for example, textbook technique sequences executed
in rapid succession, known red-team tooling paths, atomic test artifacts, or
activity confined to designated range hosts with no accompanying business
context. Note the indicators. Do NOT downgrade severity merely because you
believe it is a simulation; report both facts and let the operator decide.

Return only the JSON object matching the provided schema.
""".strip()


def build_deep_initial_prompt(case: Case, action_catalogue: str) -> list[dict[str, str]]:
    features = case.features.model_dump_json(indent=1) if case.features else "{}"
    triage = case.triage.model_dump_json(indent=1) if case.triage else "{}"
    rag_block = _format_hits(case.rag.hits if case.rag else [], limit=10)
    alert_name = case.alert.search_name if case.alert else "unknown"
    host = case.alert.primary_host() if case.alert else None

    user = f"""CASE {case.case_id}
Detection rule: {alert_name}
Primary host: {host or 'not identified'}

EXTRACTED FEATURES:
{features}

TRIAGE VERDICT (fast path, Spark 1):
{triage}

RETRIEVED ATT&CK CONTEXT:
{rag_block}

AVAILABLE EVIDENCE COLLECTION ACTIONS:
{action_catalogue}

Begin your analysis. State hypotheses and decide whether to collect evidence or
conclude."""
    return [
        {"role": "system", "content": DEEP_SYSTEM},
        {"role": "user", "content": user},
    ]


def build_evidence_response(results: list[dict[str, Any]]) -> str:
    """Format collected evidence for the next reasoning turn."""
    blocks: list[str] = []
    for r in results:
        status = r.get("status", "unknown")
        header = f"--- {r.get('action_id')} ({status})"
        if r.get("parameters"):
            header += f"  params={json.dumps(r['parameters'])}"
        body = str(r.get("output", ""))
        if status != "succeeded":
            body = f"COLLECTION FAILED: {r.get('reason', 'no reason given')}"
        blocks.append(f"{header}\n{_truncate(body, MAX_EVIDENCE_CHARS // max(len(results), 1))}")

    joined = "\n\n".join(blocks) if blocks else "(no evidence returned)"
    return (
        "EVIDENCE COLLECTION RESULTS:\n"
        + _wrap_untrusted(joined, "COLLECTED-EVIDENCE")
        + "\n\nUpdate your hypotheses in light of this evidence. Note that a failed "
          "collection is itself information — it does not support the hypothesis, "
          "but it also does not refute it."
    )


DEEP_CONCLUDE_INSTRUCTION = """
Produce your final verdict now. Do not request further evidence.

Your `attack_narrative` should read as a chronological account of what the
adversary (or tester) did, grounded in the specific evidence you gathered. If
the evidence does not support a narrative, say that plainly rather than
constructing one.

Recommend actions only where they follow from your conclusion. Containment
recommendations require a human approval and, on this range, will interrupt an
exercise in progress — recommend them only when a real compromise is the more
likely explanation.
""".strip()


def build_deep_conclude_prompt(history: list[dict[str, str]]) -> list[dict[str, str]]:
    return history + [{"role": "user", "content": DEEP_CONCLUDE_INSTRUCTION}]
